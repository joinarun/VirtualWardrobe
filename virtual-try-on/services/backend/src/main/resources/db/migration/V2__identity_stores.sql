CREATE TABLE vw_account (
 id UUID PRIMARY KEY, kind VARCHAR(20) NOT NULL CHECK(kind IN ('CUSTOMER','WORKFORCE')),
 name VARCHAR(120) NOT NULL, normalized_identifier VARCHAR(254) NOT NULL,
 password_hash VARCHAR(200) NOT NULL, enabled BOOLEAN NOT NULL DEFAULT TRUE,
 super_admin BOOLEAN NOT NULL DEFAULT FALSE, password_change_required BOOLEAN NOT NULL DEFAULT FALSE,
 temp_password_expires_at TIMESTAMPTZ, created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 deleted_at TIMESTAMPTZ, dataset_id VARCHAR(100),
 CONSTRAINT vw_account_identifier UNIQUE(kind,normalized_identifier),
 CONSTRAINT vw_customer_not_super CHECK(kind='WORKFORCE' OR NOT super_admin)
);
CREATE TABLE vw_recovery_code (
 id UUID PRIMARY KEY, account_id UUID NOT NULL REFERENCES vw_account(id),
 code_hash VARCHAR(64) NOT NULL UNIQUE, used_at TIMESTAMPTZ
);
CREATE TABLE vw_store (
 id UUID PRIMARY KEY,name VARCHAR(120) NOT NULL,description VARCHAR(4000) NOT NULL DEFAULT '',
 logo_url VARCHAR(2000),contact_phone VARCHAR(30),status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
 CHECK(status IN ('PENDING','ACTIVE','ARCHIVED')),created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,dataset_id VARCHAR(100)
);
CREATE TABLE vw_membership (
 id UUID PRIMARY KEY,store_id UUID NOT NULL REFERENCES vw_store(id),account_id UUID NOT NULL REFERENCES vw_account(id),
 role VARCHAR(20) NOT NULL CHECK(role IN ('STORE_ADMIN','STAFF')),
 state VARCHAR(20) NOT NULL CHECK(state IN ('INVITED','ACTIVE','REMOVED')),
 invited_by UUID REFERENCES vw_account(id),accepted_at TIMESTAMPTZ,created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 dataset_id VARCHAR(100),UNIQUE(store_id,account_id)
);
CREATE INDEX vw_membership_account_idx ON vw_membership(account_id);
CREATE TABLE vw_audit_event (
 id UUID PRIMARY KEY,actor_id UUID REFERENCES vw_account(id),store_id UUID REFERENCES vw_store(id),
 event_type VARCHAR(80) NOT NULL,subject_id UUID,created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,dataset_id VARCHAR(100)
);
CREATE TABLE vw_rate_limit (key_hash VARCHAR(64) PRIMARY KEY,window_start TIMESTAMPTZ NOT NULL,attempts INTEGER NOT NULL);
CREATE TABLE vw_administration_guard(id INTEGER PRIMARY KEY CHECK(id=1));
